#!/usr/bin/env python3
"""Generate src/hud6wa_probe/glyph_table.h from the tested Python glyphs + fit + cluster_text,
so the on-HU C renderer draws byte-identical polygons/text to the host pipeline.

    python3 -I src/cp_guide/gen_glyph_table.py [--check]

Glyph slots: 0 arrive, 1..9 = angle 0,-45,45,-90,90,-135,135,-180(u-turn L),180(u-turn R),
10..82 = roundabout exit angle -180..180 in 5-degree steps (nav_adapter quantizes the same way), 83 = exit roundabout.
"""
import os
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "hud6wa_probe"))
import glyphs as gl        # noqa: E402
import nav_adapter as na   # noqa: E402

OUT = os.path.join(HERE, "..", "hud6wa_probe", "glyph_table.h")
ANGLES = [0, -45, 45, -90, 90, -135, 135, -180, 180]


def slots():
    yield na.glyph_polys(None, 0, False)
    for a in ANGLES:
        yield na.glyph_polys(a, 0, False)
    for a in range(-180, 181, 5):
        yield na.glyph_polys(a, 0, True)
    yield na.glyph_polys("exit_round", 0, False)          # slot 83


def fold(cp):
    """cluster_text's per-character fold for U+00A0..U+017F (umlauts expand, accents drop)."""
    return unicodedata.normalize("NFKD", {"ä": "ae", "ö": "oe", "ü": "ue", "Ä": "Ae", "Ö": "Oe", "Ü": "Ue",
                                       "ß": "ss"}.get(chr(cp), chr(cp))).encode("ascii", "ignore").decode()


def render():
    pts, idx = [], []
    for polys in slots():
        assert len(polys) <= 6
        idx.append((len(pts) // 2, len(polys), [len(p) for p in polys] + [0] * (6 - len(polys))))
        for p in polys:
            for x, y in p:
                assert 0 <= x < 32768 and 0 <= y < 32768
                pts += [x, y]
    folds = [fold(cp) for cp in range(0xA0, 0x180)]
    assert all(len(f) <= 2 for f in folds)
    L = ["/* GENERATED by src/cp_guide/gen_glyph_table.py — do not edit. */",
         "#define GLYPH_ARRIVE 0", "#define GLYPH_ROUND0 10", "#define GLYPH_EXIT_ROUND 83", "#define GLYPH_N %d" % len(idx),
         "static const unsigned short G_PTS[%d] = {" % len(pts)]
    for i in range(0, len(pts), 16):
        L.append("  " + ",".join(map(str, pts[i:i + 16])) + ",")
    L.append("};")
    L.append("static const struct { unsigned short off; unsigned char npoly, len[6]; } G_IDX[%d] = {" % len(idx))
    L += ["  {%d,%d,{%s}}," % (o, n, ",".join(map(str, ln))) for o, n, ln in idx]
    L.append("};")
    L.append("/* ASCII fold for U+00A0..U+017F (cluster_text: umlauts -> ae/oe/ue/ss, accents dropped) */")
    L.append("static const char FOLD[%d][3] = {" % len(folds))
    for i in range(0, len(folds), 12):
        L.append("  " + "".join('"%s",' % f for f in folds[i:i + 12]))
    L.append("};")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    s = render()
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == s
        print("glyph_table.h up to date" if ok else "glyph_table.h STALE: rerun gen_glyph_table.py")
        sys.exit(0 if ok else 1)
    open(OUT, "w").write(s)
    print("wrote", OUT)
